"""
Example 5 - CI/CD Configuration Generator
===========================================
This script generates a GitHub Actions CI/CD YAML config
for testing and deploying an MCP server project.
It prints the config and saves it to a file.
"""

import os

# ============================================================
# Step 1: Build the GitHub Actions YAML as a string
# ============================================================

def generate_ci_config() -> str:
    """
    Generate a GitHub Actions workflow YAML for an MCP server project.
    Includes steps for linting, testing, and building.
    """
    yaml_content = """\
# GitHub Actions CI/CD for MCP Server
# Generated by example5_ci_cd_config.py

name: MCP Server CI/CD

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]

jobs:
  test:
    runs-on: ubuntu-latest

    strategy:
      matrix:
        python-version: ["3.10", "3.11", "3.12"]

    steps:
      # Step 1: Check out the code
      - name: Checkout code
        uses: actions/checkout@v4

      # Step 2: Set up Python
      - name: Set up Python ${{ matrix.python-version }}
        uses: actions/setup-python@v5
        with:
          python-version: ${{ matrix.python-version }}

      # Step 3: Install dependencies
      - name: Install dependencies
        run: |
          python -m pip install --upgrade pip
          pip install mcp
          pip install ruff  # linter

      # Step 4: Run linter
      - name: Lint with ruff
        run: |
          ruff check .

      # Step 5: Run unit tests
      - name: Run unit tests
        run: |
          python -m pytest tests/ -v

      # Step 6: Run integration tests
      - name: Run integration tests
        run: |
          python -m pytest tests/integration/ -v

  deploy:
    needs: test
    runs-on: ubuntu-latest
    if: github.ref == 'refs/heads/main'

    steps:
      - name: Checkout code
        uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: "3.12"

      - name: Install dependencies
        run: |
          python -m pip install --upgrade pip
          pip install build

      - name: Build package
        run: |
          python -m build

      - name: Deploy (placeholder)
        run: |
          echo "Deploying MCP server..."
          echo "Add your deployment commands here"
"""
    return yaml_content


# ============================================================
# Step 2: Save config to a file
# ============================================================

def save_config(yaml_content: str, output_path: str) -> str:
    """
    Save the YAML config to a file.
    Returns the absolute path of the saved file.
    """
    # Ensure the directory exists
    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)

    with open(output_path, "w") as f:
        f.write(yaml_content)

    return os.path.abspath(output_path)


# ============================================================
# Step 3: Main - generate, print, and save
# ============================================================

if __name__ == "__main__":
    print("=" * 50)
    print("CI/CD Configuration Generator")
    print("=" * 50)

    # Generate the YAML
    config = generate_ci_config()

    # Print it to the console
    print("\nGenerated GitHub Actions YAML:")
    print("-" * 50)
    print(config)
    print("-" * 50)

    # Save to file in the same directory as this script
    script_dir = os.path.dirname(os.path.abspath(__file__))
    output_file = os.path.join(script_dir, "ci_config.yml")
    saved_path = save_config(config, output_file)

    print(f"\nConfig saved to: {saved_path}")
    print("=" * 50)
